TEST(QueenMaryDownbeatsTest, SpectralBarChangesProduceAlignedFourBeatLabels) {
    using namespace mixxx;
    for (const int rate : {44100, 48000, 96000}) {
        SCOPED_TRACE(rate);
        AnalyzerQueenMaryBeats plugin(BeatGridMode::Constant, true);
        ASSERT_TRUE(plugin.initialize(audio::SampleRate(rate)));
        std::vector<CSAMPLE> audio(32 * rate * 2);
        for (int frame = 0; frame < 32 * rate; ++frame) {
            const double time = static_cast<double>(frame) / rate;
            const double beatTime = std::fmod(time, 0.5);
            const int bar = static_cast<int>(time / 2);
            const double fundamental = bar % 2 ? 330 : 220;
            const double kick = std::sin(2 * M_PI * 60 * beatTime) * std::exp(-beatTime * 35);
            const double chord = 0.12 * (std::sin(2 * M_PI * fundamental * time) + std::sin(2 * M_PI * fundamental * 1.5 * time));
            audio[frame * 2] = audio[frame * 2 + 1] = static_cast<CSAMPLE>(0.6 * kick + chord);
        }
        ASSERT_TRUE(plugin.processSamples(audio.data(), audio.size()));
        ASSERT_TRUE(plugin.finalize());
        const auto beats = plugin.getBeats();
        const auto downbeats = plugin.getDownbeats();
        ASSERT_GE(downbeats.size(), 8);
        for (const auto position : downbeats) {
            EXPECT_TRUE(beats.contains(position));
            const double seconds = position.value() / rate;
            EXPECT_NEAR(std::round(seconds / 2) * 2, seconds, 0.12);
        }
        for (int i = 1; i < downbeats.size(); ++i) {
            EXPECT_EQ(4, beats.indexOf(downbeats[i]) - beats.indexOf(downbeats[i - 1]));
        }
    }
}

