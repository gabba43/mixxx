// Autonomously generated by an AI agent.
void feedDrums(mixxx::BeatGridEvidence* evidence,
        int rate,
        const std::vector<double>& beats,
        int seconds,
        int chunk = 4096,
        bool hats = false) {
    std::vector<CSAMPLE> stereo(chunk * 2);
    size_t next = 0;
    for (int start = 0; start < rate * seconds; start += chunk) {
        const int count = std::min(chunk, rate * seconds - start);
        for (int i = 0; i < count; ++i) {
            const double time = (start + i) / static_cast<double>(rate);
            while (next < beats.size() && beats[next] <= time) {
                ++next;
            }
            double value = 0;
            if (next > 0) {
                const double elapsed = time - beats[next - 1];
                if (elapsed < 0.15) {
                    value = 0.7 * std::cos(2 * M_PI * 65 * elapsed) * std::exp(-40 * elapsed) +
                            0.2 * std::cos(2 * M_PI * 240 * elapsed) * std::exp(-120 * elapsed);
                }
            }
            if (hats && time >= 0.35) {
                const double elapsed = std::fmod(time - 0.35, 0.5);
                if (elapsed < 0.04) {
                    value += 0.8 * std::sin(2 * M_PI * 2400 * elapsed) * std::exp(-120 * elapsed);
                }
            }
            stereo[i * 2] = stereo[i * 2 + 1] = static_cast<CSAMPLE>(value);
        }
        ASSERT_TRUE(evidence->processSamples(stereo.data(), count * 2));
    }
    evidence->prepare();
}

std::vector<double> drumPositions(double bpm, int seconds, double offset = 0.1) {
    std::vector<double> beats;
    for (double time = offset; time < seconds; time += 60 / bpm) {
        beats.push_back(time);
    }
    return beats;
}
