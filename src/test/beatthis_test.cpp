TEST(AudioBeatGridTest, FineTimingIsMeasuredFromTheAudioAndIndependentOfChunking) {
    for (const int rate : {8000, 44100, 48000}) {
        const auto sampleRate = mixxx::audio::SampleRate(rate);
        const auto grid = mixxx::Beats::fromConstTempo(sampleRate,
                mixxx::audio::FramePos(0.1 * rate),
                mixxx::Bpm(120));
        mixxx::BeatsPointer previous;
        for (const int chunk : {500, 4096}) {
            mixxx::BeatGridEvidence evidence;
            evidence.initialize(sampleRate);
            feedDrums(&evidence, rate, drumPositions(120, 30, 0.12), 30, chunk);
            const auto result = evidence.evaluate(grid, false);
            ASSERT_TRUE(result.reliable);
            ASSERT_TRUE(result.grid);
            EXPECT_TRUE(result.grid->hasConstantTempo());
            const auto target = mixxx::audio::FramePos(10.12 * rate);
            EXPECT_NEAR(target.value(), result.grid->findClosestBeat(target).value(), 0.015 * rate);
            if (previous) {
                EXPECT_EQ(previous->firstBeat(), result.grid->firstBeat());
            }
            previous = result.grid;
        }
    }
}

TEST(AudioBeatGridTest, AGlobalHalfBeatErrorMovesTheBeatLinesAndDownbeatsTogether) {
    const auto rate = mixxx::audio::SampleRate(8000);
    auto grid = mixxx::Beats::fromConstTempo(
            rate, mixxx::audio::FramePos(0.35 * rate), mixxx::Bpm(120));
    QVector<mixxx::audio::FramePos> downbeats;
    for (double time = 0.35; time < 28; time += 2) {
        downbeats.push_back(mixxx::audio::FramePos(time * rate));
    }
    grid = grid->withDownbeats(downbeats);
    mixxx::BeatGridEvidence evidence;
    evidence.initialize(rate);
    feedDrums(&evidence, 8000, drumPositions(120, 30), 30);
    const auto result = evidence.evaluate(grid, true);
    ASSERT_TRUE(result.grid);
    EXPECT_FALSE(result.phaseChanges);
    EXPECT_TRUE(result.grid->hasConstantTempo());
    EXPECT_EQ(downbeats.size(), result.grid->getDownbeats().size());
    const auto target = mixxx::audio::FramePos(10.1 * rate);
    EXPECT_NEAR(target.value(), result.grid->findClosestBeat(target).value(), 0.015 * rate);
    for (const auto downbeat : result.grid->getDownbeats()) {
        EXPECT_LT(std::abs(std::remainder(downbeat.value() / rate - 0.1, 0.5)), 0.015);
    }
}

