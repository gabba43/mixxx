const QString kRoundingVersion = QStringLiteral("V4");

struct ClockPhase {
    double phase;
    double coherence;
};

ClockPhase measurePhase(const std::vector<double>& times,
        double bpm,
        double harmonic) {
    double real = 0;
    double imaginary = 0;
    for (const double time : times) {
        const double angle = time * bpm * harmonic * 2 * M_PI / 60;
        real += std::cos(angle);
        imaginary += std::sin(angle);
    }
    return {std::atan2(imaginary, real) * 60 / (bpm * harmonic * 2 * M_PI),
            std::hypot(real, imaginary) / times.size()};
}

double percentile(const std::vector<double>& sorted, double fraction) {
    const double index = fraction * (sorted.size() - 1);
    const auto left = static_cast<size_t>(index);
    const auto right = std::min(left + 1, sorted.size() - 1);
    return sorted[left] + (index - left) * (sorted[right] - sorted[left]);
}

struct ConstantClockFit {
    mixxx::BeatsPointer grid;
    bool constant = false;
};

// Autonomously generated by an AI agent.
// Fit a full-track clock before interpreting prediction jitter as tempo changes.
// A half-beat phase lattice tolerates metrical slips without changing the tempo.
// Persistent drift is measured over 32-beat windows; abrupt tracker phase changes
// are nuisance offsets, not evidence of acceleration. Local 64-beat regressions
// estimate constant tempo without the short-region BPM rounding used for QM.
// These thresholds express timing tolerances, not calibrated probabilities.
// End of autonomously generated text.
ConstantClockFit fitConstantClock(
        const QVector<mixxx::audio::FramePos>& beats,
        const mixxx::BeatsPointer& seed,
        const QHash<QString, QString>& extraVersionInfo,
        mixxx::audio::SampleRate sampleRate) {
    if (!seed || beats.size() < 32) {
        return {};
    }
    const double seedBpm = seed->getBpmAroundPosition(beats.front(), 1).value();
    const double duration = (beats.back() - beats.front()) / sampleRate;
    if (!(duration > 0) || !(seedBpm > 0)) {
        return {};
    }
    std::vector<double> times;
    times.reserve(beats.size());
    for (const auto beat : beats) {
        times.push_back((beat - beats.front()) / sampleRate);
    }
    std::vector<double> sampled;
    const int count = std::min(1024, static_cast<int>(times.size()));
    for (int i = 0; i < count; ++i) {
        sampled.push_back(times[static_cast<size_t>(i) * (times.size() - 1) / (count - 1)]);
    }
    double bpm = seedBpm;
    double radius = seedBpm * 0.008;
    double step = std::max(6.0 / duration, radius / 1024);
    for (int pass = 0; pass < 3; ++pass) {
        const double center = bpm;
        double best = -1;
        for (double candidate = center - radius;
                candidate <= center + radius + step * 0.1;
                candidate += step) {
            const auto phase = measurePhase(sampled, candidate, 2);
            if (phase.coherence > best) {
                best = phase.coherence;
                bpm = candidate;
            }
        }
        radius = step;
        step *= 0.1;
    }
    const double period = 60 / bpm;
    const auto clock = measurePhase(times, bpm, 2);
    struct Window {
        double time;
        double offset;
        double period;
        size_t block;
    };
    std::vector<Window> windows;
    int windowCount = 0;
    const auto windowBeats = std::min(size_t(32), times.size() / 4);
    for (size_t i = 0; i + std::max(size_t(8), windowBeats / 2) <= times.size(); i += windowBeats) {
        const auto end = std::min(i + windowBeats, times.size());
        const std::vector<double> block(times.begin() + i, times.begin() + end);
        const auto phase = measurePhase(block, bpm, 2);
        ++windowCount;
        if (phase.coherence >= 0.7) {
            windows.push_back({std::accumulate(block.begin(), block.end(), 0.0) / block.size(),
                    phase.phase,
                    (block.back() - block.front()) / (block.size() - 1),
                    i / windowBeats});
        }
    }
    bool constant = false;
    double phaseSpan = 0;
    size_t jumpCount = 0;
    if (clock.coherence >= 0.65 && windows.size() >= 4 &&
            windows.size() >= 0.8 * windowCount) {
        double previous = windows.front().offset;
        double unwrapped = previous;
        double jumps = 0;
        const double jumpThreshold = std::max(0.04, period * 0.08);
        std::vector<double> increments(windows.size());
        for (size_t i = 1; i < windows.size(); ++i) {
            increments[i] = std::remainder(
                    windows[i].offset - windows[i - 1].offset, period / 2);
        }
        for (size_t i = 0; i < windows.size(); ++i) {
            const double current = windows[i].offset;
            if (i > 0) {
                const double delta = std::remainder(current - previous, period / 2);
                unwrapped += delta;
                const auto continues = [delta](double neighbor) {
                    return neighbor * delta > 0 && std::abs(neighbor) >= std::abs(delta) * 0.5;
                };
                const bool acrossGap = windows[i].block > windows[i - 1].block + 1;
                const bool continuesBefore = continues(increments[i - 1]);
                const bool continuesAfter = i + 1 < increments.size() && continues(increments[i + 1]);
                if (std::abs(delta) > jumpThreshold &&
                        (acrossGap || (!continuesBefore && !continuesAfter))) {
                    jumps += delta;
                    ++jumpCount;
                }
            }
            windows[i].offset = unwrapped - jumps;
            previous = current;
        }
        double meanTime = 0;
        double meanOffset = 0;
        std::vector<double> localPeriods;
        for (const auto& window : windows) {
            meanTime += window.time / windows.size();
            meanOffset += window.offset / windows.size();
            localPeriods.push_back(window.period);
        }
        const double startPeriod = (localPeriods[0] + localPeriods[1]) * 0.5;
        const double endPeriod = (localPeriods[localPeriods.size() - 2] + localPeriods.back()) * 0.5;
        std::sort(localPeriods.begin(), localPeriods.end());
        const bool densityStable = percentile(localPeriods, 0.8) <= 1.25 * percentile(localPeriods, 0.2) &&
                std::max(startPeriod, endPeriod) <= 1.25 * std::min(startPeriod, endPeriod);
        double covariance = 0;
        double variance = 0;
        for (const auto& window : windows) {
            covariance += (window.time - meanTime) * (window.offset - meanOffset);
            variance += (window.time - meanTime) * (window.time - meanTime);
        }
        std::vector<double> deviations;
        for (const auto& window : windows) {
            deviations.push_back(window.offset - meanOffset -
                    covariance / variance * (window.time - meanTime));
        }
        const double startDeviation = (deviations[0] + deviations[1]) * 0.5;
        const double endDeviation = (deviations[deviations.size() - 2] + deviations.back()) * 0.5;
        std::sort(deviations.begin(), deviations.end());
        phaseSpan = percentile(deviations, 0.95) - percentile(deviations, 0.05);
        constant = densityStable && phaseSpan <= std::max(0.05, period * 0.1) &&
                std::max(std::abs(startDeviation), std::abs(endDeviation)) <= std::max(0.04, period * 0.08) &&
                jumpCount <= std::max(size_t(2), windows.size() / 8);
    }

    const auto fullPhase = measurePhase(times, bpm, 1);
    std::vector<double> localTempos;
    for (size_t start = 0; start + 64 <= times.size(); start += 64) {
        double meanIndex = 0;
        double meanTime = 0;
        for (size_t i = start; i < start + 64; ++i) {
            meanIndex += std::round((times[i] - fullPhase.phase) / period) / 64;
            meanTime += times[i] / 64;
        }
        double covariance = 0;
        double variance = 0;
        for (size_t i = start; i < start + 64; ++i) {
            const double index = std::round((times[i] - fullPhase.phase) / period);
            covariance += (index - meanIndex) * (times[i] - meanTime);
            variance += (index - meanIndex) * (index - meanIndex);
        }
        if (!(variance > 0)) {
            continue;
        }
        const double slope = covariance / variance;
        bool stable = std::abs(slope / period - 1) < 0.008;
        for (size_t i = start; stable && i < start + 64; ++i) {
            const double index = std::round((times[i] - fullPhase.phase) / period);
            stable = std::abs(times[i] - meanTime - slope * (index - meanIndex)) <= 0.04;
        }
        if (stable) {
            localTempos.push_back(60 / slope);
        }
    }
    if (clock.coherence >= 0.65 && localTempos.size() >= 4) {
        std::sort(localTempos.begin(), localTempos.end());
        const auto trim = localTempos.size() / 10;
        const double localBpm = std::accumulate(localTempos.begin() + trim, localTempos.end() - trim, 0.0) /
                (localTempos.size() - trim * 2);
        if (jumpCount > 0 || std::abs(bpm / localBpm - 1) * duration <= 0.025) {
            bpm = localBpm;
        }
    }
    const auto anchor = measurePhase(times, bpm, 1);
    double first = std::fmod(beats.front().value() + anchor.phase * sampleRate,
            60 * sampleRate / bpm);
    if (first < 0) {
        first += 60 * sampleRate / bpm;
    }
    auto grid = mixxx::Beats::fromConstTempo(sampleRate,
            mixxx::audio::FramePos(first).toNearestFrameBoundary(),
            mixxx::Bpm(bpm),
            BeatFactory::getPreferredSubVersion(extraVersionInfo));
    qDebug() << "Auto clock fit:" << bpm << "BPM; coherence" << clock.coherence
             << "phase span" << phaseSpan * 1000 << "ms; constant" << constant;
    return {grid, constant};
}

